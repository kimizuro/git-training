int	ft_strcmp(char *s1, char *s2)
{
	int	i;

	i = 0;
	while (s1[i] != '\0' && s2[i] != '\0' && s1[i] == s2[i])
	{
		i++;
	}
	return (s1[i] - s2[i]);
}
#include <stdio.h>
int main(int argc, char **argv)
{
	if (argc != 3)
		return (1);
	printf("%d", ft_strcmp(argv[1], argv[2]));
}

