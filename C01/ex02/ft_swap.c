void	ft_swap(int *a, int *b)
{
	int	temp;

	temp = *a;
	*a = *b;
	*b = temp;
}
#include <stdio.h>
int main(void)
{
	int i = 45;
	int j = 5;
	ft_swap(&i, &j);
	printf("%d, %d", i, j);
}
