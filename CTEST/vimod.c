#include <stdio.h>

void ft_swap(int *a, int *b)
{
	int temp;

	temp = *a;
	*a =*b;
	*b = temp;
}
int main(void)
{
	int i = 17;
	int j = 3;
	ft_swap(&i, &j);
	printf("%d  %d", i, j);
	return 0;
}
